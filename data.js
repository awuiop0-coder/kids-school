// ตัวช่วยสร้างกล่องคำ  [ ["ก","ไก่","🐔"], ... ]
function chips(arr) {
  return '<div class="chips">' + arr.map(function (x) {
    return '<div class="chip"><b>' + x[0] + '</b>' + x[1] + '<span class="e">' + (x[2] || '') + '</span></div>';
  }).join('') + '</div>';
}
function emoChips(arr) { // [ ["Red","สีแดง","🔴"] ]
  return '<div class="chips">' + arr.map(function (x) {
    return '<div class="chip"><span class="e">' + x[2] + '</span><b style="font-size:22px">' + x[0] + '</b>' + x[1] + '</div>';
  }).join('') + '</div>';
}

